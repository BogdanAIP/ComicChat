import fs from 'node:fs'

function read(path) {
  return fs.readFileSync(path, 'utf8')
}

function assertIncludes(text, needle, label) {
  if (!text.includes(needle)) {
    throw new Error(`PR-09 gate: missing ${label}: ${needle}`)
  }
}

const mcp = read('supabase/functions/comicchat-mcp/index.ts')
const ui = read('supabase/functions/comicchat-mcp/ui.ts')
const pkg = JSON.parse(read('package.json'))

for (const required of [
  "'open_comicchat_app'",
  "'ui://comicchat/app-v2.html'",
  "server.registerResource(",
  "mimeType: 'text/html;profile=mcp-app'",
  "ui: { resourceUri: COMICCHAT_APP_URI }",
  "entrypoints: [{ type: 'global' }, { type: 'thread' }]",
  "availableDisplayModes: ['inline', 'fullscreen']",
  "securitySchemes: oauth",
]) {
  assertIncludes(mcp, required, 'Plugin Extension resource/tool contract')
}

const main = read('mcp-ui/main.jsx')
const adapter = read('mcp-ui/client.mjs')
const manifest = JSON.parse(read('mcp-ui/build-manifest.json'))
for (const component of ['pages/index.js', 'components/ComicDirectMessages.js',
  'components/ComicGroupChat.js', 'components/ComicPanel.js',
  'components/ComicStylePicker.js', 'components/ComicStoryFeed.js', 'components/Profile.js']) {
  if (!manifest.inputs.includes(component)) throw new Error('Shared website component absent: ' + component)
}
assertIncludes(main, "from '@modelcontextprotocol/ext-apps'", 'standard MCP Apps bridge')
assertIncludes(main, 'bridge.callServerTool(request)', 'host-only data transport')
assertIncludes(adapter, "'comicchat_ui_read'", 'fixed read capabilities')
assertIncludes(adapter, "'comicchat_ui_write'", 'fixed write capabilities')
assertIncludes(ui, 'Generated by npm run plugin:build-ui', 'generated shared UI')
for (const forbidden of [
  'NEXT_PUBLIC_SUPABASE',
  'SUPABASE_SERVICE_ROLE_KEY',
  'Authorization:',
  'sessionStorage',
  'OPENAI_API_KEY',
]) {
  if (ui.includes(forbidden)) {
    throw new Error(`PR-09 gate: UI must not contain direct credential/storage path: ${forbidden}`)
  }
}

if (pkg.scripts?.['extension:pr09'] !== 'node scripts/pr09-extension-ui-check.mjs') {
  throw new Error('PR-09 gate: extension:pr09 script missing or changed')
}

console.log('PR-09 Plugin Extension UI boundaries: PASS')

const preferences = read('utils/usePreferences.jsx')
assertIncludes(preferences, "'comicchat:preferences:'", 'account-scoped nonsecret preference cache')
assertIncludes(preferences, "JSON.stringify(next)", 'only normalized locale/theme are cached')
if(/token|password|email|original_text|draft/i.test(preferences)) throw new Error('Preference cache must not store credentials or private conversations')
